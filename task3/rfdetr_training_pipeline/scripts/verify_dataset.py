import os
import json
import yaml
from pathlib import Path
from collections import defaultdict

def load_config(config_path):
    with open(config_path, 'r') as f:
        return yaml.safe_load(f)

def verify_coco_json(json_path, image_dir, ontology, split_name, report_lines):
    if not os.path.exists(json_path):
        report_lines.append(f"## {split_name} Split")
        report_lines.append(f"❌ CRITICAL: COCO JSON not found at `{json_path}`\n")
        return False
        
    with open(json_path, 'r') as f:
        data = json.load(f)
        
    report_lines.append(f"## {split_name} Split")
    
    issues = []
    
    # Check ontology
    dataset_categories = {cat["id"]: cat["name"] for cat in data.get("categories", [])}
    for cat_id, cat_name in dataset_categories.items():
        if cat_name not in ontology:
            issues.append(f"Invalid category found: `{cat_name}` (ID: {cat_id}) is not in official ontology.")
            
    # Check image uniqueness and existence
    image_ids = set()
    filenames = set()
    image_dict = {}
    
    for img in data.get("images", []):
        img_id = img.get("id")
        filename = img.get("file_name")
        w = img.get("width", 0)
        h = img.get("height", 0)
        
        if img_id in image_ids:
            issues.append(f"Duplicate Image ID: {img_id}")
        image_ids.add(img_id)
        
        if filename in filenames:
            issues.append(f"Duplicate filename: {filename}")
        filenames.add(filename)
        
        image_dict[img_id] = img
        
        if w <= 0 or h <= 0:
            issues.append(f"Image {filename} has invalid dimensions: {w}x{h}")
            
        img_path = os.path.join(image_dir, filename)
        if not os.path.exists(img_path):
            issues.append(f"Image file missing from disk: {filename}")
            
    # Check annotations
    ann_ids = set()
    for ann in data.get("annotations", []):
        ann_id = ann.get("id")
        img_id = ann.get("image_id")
        cat_id = ann.get("category_id")
        bbox = ann.get("bbox", [])
        
        if ann_id in ann_ids:
            issues.append(f"Duplicate Annotation ID: {ann_id}")
        ann_ids.add(ann_id)
        
        if img_id not in image_dict:
            issues.append(f"Orphan annotation {ann_id}: Image ID {img_id} not found.")
            
        if cat_id not in dataset_categories:
            issues.append(f"Annotation {ann_id} has invalid category ID: {cat_id}")
            
        if len(bbox) != 4 or bbox[2] <= 0 or bbox[3] <= 0:
            issues.append(f"Annotation {ann_id} has invalid bbox: {bbox}")
            
    if issues:
        report_lines.append(f"⚠️ Found {len(issues)} issues:")
        for issue in issues[:20]:
            report_lines.append(f"- {issue}")
        if len(issues) > 20:
            report_lines.append(f"- ...and {len(issues) - 20} more.")
    else:
        report_lines.append("✅ All checks passed (No duplicates, missing files, or bad bboxes).")
        
    report_lines.append(f"- Total Images: {len(data.get('images', []))}")
    report_lines.append(f"- Total Annotations: {len(data.get('annotations', []))}\n")
    return len(issues) == 0

def main():
    script_dir = Path(__file__).parent
    workspace = script_dir.parent
    config_path = workspace / "configs" / "dataset_config.yaml"
    report_path = workspace / "documentation" / "dataset_validation_report.md"
    
    config = load_config(config_path)
    ontology = set(config["class_names"])
    
    report_lines = [
        "# Dataset Validation Report",
        "Generated by `verify_dataset.py` to ensure complete COCO JSON integrity.",
        ""
    ]
    
    splits = [
        ("Train", config.get("train_annotations"), config.get("train_images")),
        ("Validation", config.get("val_annotations"), config.get("val_images")),
        ("Test", config.get("test_annotations"), config.get("test_images"))
    ]
    
    all_passed = True
    for name, ann_path, img_dir in splits:
        if ann_path and img_dir:
            passed = verify_coco_json(ann_path, img_dir, ontology, name, report_lines)
            if not passed:
                all_passed = False
                
    with open(report_path, "w", encoding="utf-8") as f:
        f.write("\n".join(report_lines))
        
    print(f"Validation complete. Report saved to {report_path}")
    if not all_passed:
        print("WARNING: Dataset validation found errors. Check the report.")
    
if __name__ == "__main__":
    main()
