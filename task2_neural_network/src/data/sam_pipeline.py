"""
SAM Mask Pipeline Integration.

This module provides utilities to ingest masks generated by the existing
Segment Anything Model (SAM) pipeline into the Structural Mask Classifier
dataset structure and metadata system.
"""

import os
import shutil
import cv2
from pathlib import Path
from typing import List, Tuple

from src.data.metadata_mgr import MetadataManager, ImageMetadata, MaskMetadata
from src.utils.logger import get_logger

logger = get_logger(__name__)

class SAMPipelineIngestor:
    """Ingests raw images and SAM-generated masks into the project dataset."""

    def __init__(self, project_root: str | Path):
        """
        Initializes the ingestor with the project root to determine standard paths.
        
        Args:
            project_root (str | Path): Root directory of the neural network project.
        """
        self.project_root = Path(project_root)
        self.raw_img_dir = self.project_root / "data" / "raw" / "images"
        self.raw_mask_dir = self.project_root / "data" / "raw" / "masks"
        self.metadata_path = self.project_root / "data" / "metadata" / "dataset_metadata.json"
        
        # Ensure directories exist
        self.raw_img_dir.mkdir(parents=True, exist_ok=True)
        self.raw_mask_dir.mkdir(parents=True, exist_ok=True)
        
        self.metadata_mgr = MetadataManager(self.metadata_path)

    def ingest_image_and_masks(self, image_path: str | Path, mask_paths: List[str | Path], image_id: str) -> None:
        """
        Copies an image and its corresponding SAM masks into the project data folder
        and updates the metadata system.
        
        Args:
            image_path (str | Path): Path to the original input image.
            mask_paths (List[str | Path]): Paths to the generated binary masks.
            image_id (str): Unique identifier for this image.
        """
        image_path = Path(image_path)
        if not image_path.exists():
            logger.error(f"Image not found at {image_path}")
            raise FileNotFoundError(f"Image not found at {image_path}")

        # Read image to get resolution
        img = cv2.imread(str(image_path))
        if img is None:
            logger.error(f"Failed to read image at {image_path}")
            raise ValueError(f"Invalid image: {image_path}")
        
        resolution = (img.shape[1], img.shape[0]) # Width, Height
        
        # Copy image to raw dataset
        dest_image_path = self.raw_img_dir / f"{image_id}{image_path.suffix}"
        shutil.copy2(image_path, dest_image_path)
        logger.debug(f"Copied image to {dest_image_path}")

        masks_metadata = []
        for i, m_path in enumerate(mask_paths):
            m_path = Path(m_path)
            if not m_path.exists():
                logger.warning(f"Mask not found at {m_path}. Skipping.")
                continue
                
            mask_id = f"{image_id}_mask_{i:04d}"
            dest_mask_path = self.raw_mask_dir / f"{mask_id}{m_path.suffix}"
            shutil.copy2(m_path, dest_mask_path)
            
            # Create relative path for metadata to maintain portability
            rel_mask_path = dest_mask_path.relative_to(self.project_root).as_posix()
            
            mask_meta = MaskMetadata(
                mask_id=mask_id,
                mask_path=rel_mask_path,
                label="unlabeled"
            )
            masks_metadata.append(mask_meta)
            logger.debug(f"Copied mask to {dest_mask_path}")

        rel_img_path = dest_image_path.relative_to(self.project_root).as_posix()
        
        image_meta = ImageMetadata(
            image_id=image_id,
            image_path=rel_img_path,
            resolution=resolution,
            masks=masks_metadata
        )
        
        self.metadata_mgr.add_image(image_meta)
        logger.info(f"Successfully ingested image {image_id} with {len(masks_metadata)} masks.")

if __name__ == "__main__":
    # Example usage / Stub for testing
    print("SAMPipelineIngestor module ready.")
